/**
 * Returns all cultural cards matching a given country code (e.g. 'POR', 'BRA', 'GER', etc.)
 */
export function getCulturalCardsForCountry(countryCode?: string): CulturalCardDefinition[] {
  if (!countryCode) return [];
  const normalized = countryCode.trim().toUpperCase();
  if (CULTURAL_CARDS_CATALOG[normalized]) {
    return CULTURAL_CARDS_CATALOG[normalized];
  }
  // Fallbacks for UK variations (ENG, SCO, GBR)
  if (normalized === 'GBR' || normalized === 'SCO' || normalized === 'WAL' || normalized === 'NIR') {
    return CULTURAL_CARDS_CATALOG['ENG'] || [];
  }
  return [];
}

/**
 * Converts a CulturalCardDefinition into a CareerStageCardInstance
 */
export function convertCulturalCardToInstance(
  card: CulturalCardDefinition,
  instanceId?: string
): CareerStageCardInstance {
  return {
    id: instanceId || `cultural_${card.id}_${Date.now()}_${Math.floor(Math.random() * 1000)}`,
    name: card.name,
    category: card.category,
    type: card.type,
    rarity: card.rarity === 'Diamond' ? 'Legendary' : card.rarity,
    description: card.description,
    effects: card.effects,
    designColor: card.designColor,
    iconName: card.iconName,
    isCulturalCard: true,
    culturalCountry: card.countryCode,
    culturalFlavor: card.culturalFlavor,
    flagEmoji: card.flagEmoji,
    modifiers: {
      ...card.modifiers,
      isCulturalCard: true,
      culturalCountry: card.countryCode,
      culturalFlavor: card.culturalFlavor,
      flagEmoji: card.flagEmoji,
    },
  };
}

/**
 * Evaluates whether to draw a cultural card for the player's host country (10% chance)
 */
export function maybeDrawCulturalCard(
  countryCode: string | undefined,
  rarityBias?: 'Bronze' | 'Silver' | 'Gold' | 'Diamond'
): CareerStageCardInstance | null {
  const cards = getCulturalCardsForCountry(countryCode);
  if (!cards || cards.length === 0) return null;

  // Filter by rarity bias if specified, else pick uniformly
  let pool = cards;
  if (rarityBias) {
    const matched = cards.filter((c) => c.rarity === rarityBias);
    if (matched.length > 0) pool = matched;
  }

  const chosen = pool[Math.floor(Math.random() * pool.length)];
  return convertCulturalCardToInstance(chosen);
}
